"""Rebuild js/data.js from a new LUMA "Resumen Metricas Master" workbook.

Usage:  python build_data.py path/to/Resumen-Metricas-Master.xlsx
Needs:  pip install pandas openpyxl
"""
import sys, json, pathlib
import numpy as np, pandas as pd

xlsx = sys.argv[1]
df = pd.read_excel(xlsx, sheet_name='T&D')
months = [c for c in df.columns if hasattr(c, 'year')]
df['Metric'] = df['Metric'].astype(str).str.strip()
df['Sub-Group'] = df['Sub-Group'].fillna('').astype(str).str.strip()
long = df.melt(id_vars=['Metric', 'Sub-Group'], value_vars=months, var_name='month', value_name='value')
long['value'] = pd.to_numeric(long['value'], errors='coerce')
long = long.dropna(subset=['value'])
long['month'] = pd.to_datetime(long['month'])
long['fy'] = 'FY' + np.where(long.month.dt.month >= 7, long.month.dt.year + 1, long.month.dt.year).astype(str)
long['month'] = long.month.dt.strftime('%Y-%m')

def rows(m, s): return long[(long.Metric == m) & (long['Sub-Group'] == s)]
def annual(m, s, rule):
    out = {}
    for fy, g in rows(m, s).groupby('fy'):
        if fy < 'FY2022': continue
        june = g[g.month.str[5:7] == '06']
        if june.empty or (rule != 'end' and len(g) < 10): continue
        v = {'end': june.value.iloc[0], 'avg': g.value.mean(), 'sum': g.value.sum()}[rule]
        out[fy] = round(float(v), 4)
    return out
def monthly(m, s): return [[r.month, round(float(r.value), 4)] for r in rows(m, s).sort_values('month').itertuples()]

SPEC = {
 'saidi': ('SAIDI (T&D FYTD)', 'System', 'end'), 'saifi': ('SAIFI (T&D FYTD)', 'System', 'end'),
 'caidi': ('Monthly CAIDI', '', 'avg'), 'veg': ('Vegetation Maintenance Miles Completed (FYTD)', 'System', 'end'),
 'calls': ('Percent of customer calls answered', '', 'avg'), 'abandon': ('Call abandonment rate (FYTD)', '', 'end'),
 'asa': ('Average speed of answer (FYTD)', '', 'end'), 'complaints': ('Customer Complaint Rate (FYTD)', '', 'end'),
 'estimated': ('Percent of bills estimated vs. read', '', 'avg'),
 'dispute': ('Average time to resolve billing disputes (Act 57 Claims)', '', 'avg'),
 'act57': ('Number of Act 57 Claims Opened', '', 'sum'), 'fatal': ('OSHA Fatalities (FYTD)', '', 'end'),
 'osha': ('OSHA Recordable Incident Rate (FYTD)', '', 'end'), 'dart': ('OSHA DART Rate (FYTD)', '', 'end'),
 'backlog': ('Net monthly work orders balance', '', 'end'), 'losses': ('Technical losses as % of net generation', '', 'avg'),
 'fleet': ('Fleet out of service (system)', '', 'avg'), 'headcount': ('Actual headcounts by employee type', 'Total', 'end'),
 'headcount_budget': ('Budgeted headcounts by employee type', 'Total', 'end'),
 'customers': ('Number of customers by customer class', 'Total', 'end'),
 'solar': ('Total installed distributed generation capacity - Photovoltaic', 'Total', 'end'),
 'solar_sites': ('Total number of distributed generation installations - Photovoltaic', 'Total', 'end'),
 'bess': ('Total number of BESS installations', 'Total', 'end'),
 'disconnects': ('Number of disconnections by customer class', 'Total', 'sum'),
}
ann = {k: annual(*v) for k, v in SPEC.items()}
years = sorted(ann['saidi'])  # complete fiscal years (have a June value)

reg = {}
r = long[(long.Metric == 'Monthly SAIDI (T&D)') & (long['Sub-Group'] != 'System')]
for (sg, fy), g in r.groupby(['Sub-Group', 'fy']):
    if len(g) == 12: reg.setdefault(sg, {})[fy] = round(float(g.value.sum()), 2)

data = {
 'meta': {'title': 'Puerto Rico Grid Report Card', 'source': 'LUMA monthly performance-metrics workbook, Energy Bureau case NEPR-MI-2019-0007',
          'dataThrough': long.month.max(), 'firstMonth': long.month.min(), 'years': years, 'latestYear': years[-1]},
 'annual': ann,
 # FY2020 baselines and benchmarks: Energy Bureau, NEPR-MI-2019-0007 (May 21, 2021; restated Dec 26, 2024)
 'baselines': {'saidi': {'baseline': 1243, 'benchmark': 102}, 'saifi': {'baseline': 10.6, 'benchmark': 1.0},
   'caidi': {'baseline': 117, 'benchmark': 101}, 'calls': {'baseline': None, 'benchmark': 1.0},
   'asa': {'baseline': 8.25, 'benchmark': 0.4}, 'estimated': {'baseline': 0.094, 'benchmark': 0.05},
   'dispute': {'baseline': None, 'benchmark': 60}, 'osha': {'baseline': 6.9, 'benchmark': 2.3},
   'dart': {'baseline': 4.77, 'benchmark': 1.1}, 'fatal': {'baseline': 0, 'benchmark': 0}},
 'monthly': {'saidi': monthly('Monthly SAIDI (T&D)', 'System'), 'calls': monthly('Percent of customer calls answered', ''),
   'solar': monthly('Total installed distributed generation capacity - Photovoltaic', 'Total'),
   'bess': monthly('Total number of BESS installations', 'Total')},
 'regions': [{'name': k, 'minutes': v} for k, v in sorted(reg.items())],
}
out = pathlib.Path(__file__).resolve().parent / 'data.js'
out.write_text('/* Generated by tools/build_data.py. Fiscal years run July-June. */\nwindow.GRID_DATA = '
               + json.dumps(data, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
print(f'Wrote {out} — latest complete year {years[-1]}, data through {data["meta"]["dataThrough"]}')
